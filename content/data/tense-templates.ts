import { S, np, type Subject, type Tense } from '../../src/lib/generators/conjugate';
import type { LevelT } from '../../src/lib/schema';

/**
 * Sentence templates for the tense generator.
 *
 * Each template fixes the context (time markers, linked clauses) so that the
 * tenses in `accept` are correct and the tenses in `reject` are clearly
 * wrong. Every verb + complement pair ("frame") was chosen to be natural with
 * every subject in the template's pool. Stative frames automatically move
 * continuous tenses from `accept` to `reject`.
 */

export interface TenseFrame {
  v: string;
  o?: string;
  /** Fixed subject (otherwise one is drawn from the template's pool). */
  s?: Subject;
  stative?: boolean;
}

export interface TenseTemplate {
  id: string;
  topic: 'present-past' | 'perfect-tenses' | 'narrative-tenses' | 'future';
  ref: string;
  level: LevelT;
  difficulty: number;
  /** {S} subject · {V} verb phrase (the gap) · {O} complement. */
  text: string;
  subjects?: Subject[];
  frames: TenseFrame[];
  accept: Tense[];
  reject: Tense[];
  negative?: boolean;
  explanation: string;
}

